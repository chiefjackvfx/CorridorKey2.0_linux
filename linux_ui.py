class Section(QWidget):
    def __init__(self, title, expanded=True):
        super().__init__()
        layout = QVBoxLayout(self)
        layout.setContentsMargins(8, 3, 8, 3)
        toggle = QToolButton()
        toggle.setText(title)
        toggle.setCheckable(True)
        toggle.setChecked(expanded)
        toggle.setToolButtonStyle(Qt.ToolButtonTextBesideIcon)
        toggle.setArrowType(Qt.DownArrow if expanded else Qt.RightArrow)
        toggle.setObjectName('sectionTitle')
        toggle.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)
        layout.addWidget(toggle)
        body = QWidget()
        self.form = QFormLayout(body)
        self.form.setContentsMargins(5, 8, 0, 4)
        self.form.setSpacing(7)
        self.form.setFieldGrowthPolicy(QFormLayout.AllNonFixedFieldsGrow)
        layout.addWidget(body)
        body.setVisible(expanded)
        toggle.toggled.connect(body.setVisible)
        toggle.toggled.connect(lambda value: toggle.setArrowType(Qt.DownArrow if value else Qt.RightArrow))


def slider_control(spin, maximum=100):
    row = QHBoxLayout()
    slider = QSlider(Qt.Horizontal)
    slider.setRange(0, maximum)
    slider.setValue(round(spin.value()*100))
    slider.valueChanged.connect(lambda value: spin.setValue(value/100))
    spin.valueChanged.connect(lambda value: slider.setValue(round(value*100)))
    spin.setFixedWidth(76)
    row.addWidget(slider, 1)
    row.addWidget(spin)
    return row


